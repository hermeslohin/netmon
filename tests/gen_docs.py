#!/usr/bin/env python3
"""Generate docs/TEST_TRACEABILITY.md (requirements <-> tests) and the test inventory in docs/TESTING.md.

Reads tests/requirements.py and the REQ: tags in every test docstring (static parse - nothing is executed).
Optional: --results <json> (written by tests/run_tests.py) adds the pass/fail status of each test.

Usage: python3 tests/gen_docs.py [--results tests/.last_results.json] [--check]
  --check   exit 1 if any test has no/unknown REQ tag or any requirement has no test (CI gate)
"""
import ast
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from requirements import REQUIREMENTS  # noqa: E402

REQ_RE = re.compile(r"REQ:\s*([A-Z]+-\d+(?:\s*,\s*[A-Z]+-\d+)*)")
BEGIN, END = "<!-- BEGIN GENERATED INVENTORY -->", "<!-- END GENERATED INVENTORY -->"


def collect():
    tests = []
    for level in ("unit", "e2e"):
        for path in sorted(glob.glob(os.path.join(HERE, level, "test_*.py"))):
            mod = os.path.splitext(os.path.basename(path))[0]
            tree = ast.parse(open(path).read())
            mdoc = (ast.get_docstring(tree) or "").strip().splitlines()
            for cls in [n for n in tree.body if isinstance(n, ast.ClassDef)]:
                cdoc = (ast.get_docstring(cls) or "").strip().splitlines()
                for fn in [n for n in cls.body if isinstance(n, ast.FunctionDef) and n.name.startswith("test")]:
                    doc = ast.get_docstring(fn) or ""
                    m = REQ_RE.search(doc)
                    xfail = any((isinstance(d, ast.Attribute) and d.attr == "expectedFailure") for d in fn.decorator_list)
                    tests.append({
                        "level": level, "module": mod, "class": cls.name, "name": fn.name,
                        "id": f"{level}.{mod}.{cls.name}.{fn.name}",
                        "summary": (doc.strip().splitlines() or [""])[0].strip(),
                        "reqs": [r.strip() for r in m.group(1).split(",")] if m else [],
                        "xfail": xfail, "class_doc": cdoc[0] if cdoc else "", "module_doc": mdoc[0] if mdoc else "",
                        "path": os.path.relpath(path, REPO),
                    })
    return tests


def status_of(t, results):
    if not results:
        return "expected failure (known bug)" if t["xfail"] else ""
    return results.get(t["id"], "not run")


def traceability(tests, results):
    by_req = {r: [] for r in REQUIREMENTS}
    for t in tests:
        for r in t["reqs"]:
            by_req.setdefault(r, []).append(t)
    n_cov = sum(1 for r in REQUIREMENTS if by_req[r])
    out = ["# netmon test traceability matrix", "",
           "Generated by `tests/gen_docs.py` from `tests/requirements.py` and the `REQ:` tags in each test's docstring "
           "- do not edit by hand. How the tests work: [TESTING.md](TESTING.md).", "",
           f"**{len(REQUIREMENTS)} requirements, {n_cov} covered ({100 * n_cov // len(REQUIREMENTS)}%), "
           f"{len(tests)} tests ({sum(t['level'] == 'unit' for t in tests)} unit, {sum(t['level'] == 'e2e' for t in tests)} end-to-end).**", ""]
    if results:
        cnt = {}
        for t in tests:
            s = status_of(t, results)
            cnt[s] = cnt.get(s, 0) + 1
        out += ["Last run: " + ", ".join(f"{v} {k}" for k, v in sorted(cnt.items())), ""]
    out += ["## Summary", "", "| Req | Area | Requirement | Source | Unit | E2E |", "|---|---|---|---|---|---|"]
    for r, (area, text, src) in REQUIREMENTS.items():
        ts = by_req[r]
        u, e = sum(t["level"] == "unit" for t in ts), sum(t["level"] == "e2e" for t in ts)
        flag = "" if ts else " ⚠️ **not covered**"
        out.append(f"| [{r}](#{r.lower()}) | {area} | {text}{flag} | {src} | {u} | {e} |")
    out += ["", "## Requirement → tests", ""]
    for r, (area, text, src) in REQUIREMENTS.items():
        out += [f"### {r}", "", f"**{area}:** {text} _(source: {src})_", ""]
        ts = by_req[r]
        if not ts:
            out += ["_No test yet._", ""]
            continue
        out += ["| Level | Test | Verifies | Status |", "|---|---|---|---|"]
        for t in sorted(ts, key=lambda t: (t["level"] != "unit", t["id"])):
            out.append(f"| {t['level']} | `{t['module']}.{t['class']}.{t['name']}` | {t['summary']} | {status_of(t, results)} |")
        out.append("")
    unknown = sorted({r for t in tests for r in t["reqs"] if r not in REQUIREMENTS})
    untagged = [t["id"] for t in tests if not t["reqs"]]
    out += ["## Test → requirements", "", "| Test | Requirements |", "|---|---|"]
    for t in tests:
        out.append(f"| `{t['id']}` | {', '.join(t['reqs']) or '—'} |")
    out += ["", "## Gaps", "",
            f"- Requirements without a test: {', '.join(r for r in REQUIREMENTS if not by_req[r]) or 'none'}",
            f"- Tests without a REQ tag: {', '.join(untagged) or 'none'}",
            f"- Unknown REQ ids used: {', '.join(unknown) or 'none'}",
            f"- Expected failures (documented app bugs): {', '.join('`' + t['id'] + '`' for t in tests if t['xfail']) or 'none'}", ""]
    return "\n".join(out), untagged, unknown, [r for r in REQUIREMENTS if not by_req[r]]


def inventory(tests):
    out = [BEGIN, "", "_Generated by `tests/gen_docs.py`._", ""]
    for level, title in (("unit", "Unit tests"), ("e2e", "End-to-end tests")):
        out += [f"### {title}", "", "| File | Tests | Covers |", "|---|---|---|"]
        mods = {}
        for t in tests:
            if t["level"] == level:
                mods.setdefault(t["path"], []).append(t)
        for p, ts in mods.items():
            reqs = sorted({r for t in ts for r in t["reqs"]})
            out.append(f"| `{p}` | {len(ts)} | {ts[0]['module_doc'] or ts[0]['class_doc']} ({', '.join(reqs)}) |")
        out.append("")
    out.append(END)
    return "\n".join(out)


def main():
    results = None
    if "--results" in sys.argv:
        results = json.load(open(sys.argv[sys.argv.index("--results") + 1]))
    tests = collect()
    md, untagged, unknown, uncovered = traceability(tests, results)
    with open(os.path.join(REPO, "docs", "TEST_TRACEABILITY.md"), "w") as f:
        f.write(md)
    tp = os.path.join(REPO, "docs", "TESTING.md")
    if os.path.exists(tp):
        s = open(tp).read()
        if BEGIN in s and END in s:
            s = s[:s.index(BEGIN)] + inventory(tests) + s[s.index(END) + len(END):]
            with open(tp, "w") as f:
                f.write(s)
    print(f"{len(tests)} tests, {len(REQUIREMENTS) - len(uncovered)}/{len(REQUIREMENTS)} requirements covered; "
          f"untagged={len(untagged)} unknown={unknown} uncovered={uncovered}")
    if "--check" in sys.argv and (untagged or unknown or uncovered):
        sys.exit(1)


if __name__ == "__main__":
    main()
